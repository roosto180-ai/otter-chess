"""Choose among saved training checkpoints using all validation Elo cells; test once."""
import argparse,hashlib,json
from pathlib import Path
import torch
from safetensors.torch import save_file
from finetune_blitz import evaluate
from train import build_model

def main():
    p=argparse.ArgumentParser(); p.add_argument('--run',required=True); p.add_argument('--data',required=True)
    p.add_argument('--baseline',required=True); p.add_argument('--device',default='cpu')
    a=p.parse_args(); root=Path(a.run); device=torch.device(a.device); torch.set_num_threads(8)
    model=build_model(20).to(device); choices=[]; best=float('inf'); best_file=None
    for path in sorted((root/'policy_model').glob('step_*.pt'),key=lambda x:int(x.stem.split('_')[-1])):
        # These are trusted checkpoints generated by our local training process.
        state=torch.load(path,map_location='cpu',weights_only=False)
        model.load_state_dict(state['model_state_dict'],strict=True)
        metrics=evaluate(model,a.data,'validation',None,device)
        score=sum(x['nll'] for x in metrics.values())/len(metrics)
        choices.append({'step':state['step'],'macro_nll':score,'validation':metrics})
        print(json.dumps({'step':state['step'],'validation_macro_nll':score}),flush=True)
        if score<best: best=score; best_file=path
    assert best_file is not None
    chosen=torch.load(best_file,map_location='cpu',weights_only=False); model.load_state_dict(chosen['model_state_dict'],strict=True)
    save_file({k:v.cpu().contiguous() for k,v in model.state_dict().items()},str(root/'selected.safetensors'))
    report=json.loads(Path(a.baseline).read_text(encoding='utf-8'))
    report['selection']={'criterion':'Mean NLL across all 22 validation time-group/Elo cells','selected_step':chosen['step'],'candidates':choices}
    report['candidate']={'validation':next(c['validation'] for c in choices if c['step']==chosen['step']),
                         'test':evaluate(model,a.data,'test',None,device)}
    report['candidate_step']=chosen['step']
    report['candidate_sha256']=hashlib.sha256((root/'selected.safetensors').read_bytes()).hexdigest()
    report['strength_verified']=False
    (root/'selected-comparison.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(f'Selected step {chosen["step"]}; saved selected.safetensors',flush=True)

if __name__=='__main__': main()
